function hydrateIcons() {
  document.querySelectorAll('.ui-icon[data-icon]').forEach((slot) => {
    if (slot.querySelector('svg')) return;
    const name = slot.getAttribute('data-icon') || '';
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    svg.innerHTML = iconPaths[name] || iconPaths.sparkles;
    slot.append(svg);
  });
}

function getSafeStorage() {
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

function mountProjectDemo(fallback) {
  const base = `/assets/media/${encodeURIComponent(fallback.dataset.projectDemo)}`;
  const video = document.createElement('video');
  video.controls = video.playsInline = video.loop = true;
  video.defaultMuted = video.muted = true;
  video.preload = 'metadata';
  fallback.replaceWith(video);

  // A second switch before metadata arrives must not replace the saved time with zero.
  let pendingTime = 0;
  video.addEventListener('loadedmetadata', () => {
    if (pendingTime) {
      video.currentTime = pendingTime;
      pendingTime = 0;
    }
  });

  return (theme) => {
    const variant = theme === 'dark' ? `${base}-dark` : base;
    const src = `${variant}.mp4`;
    if (video.getAttribute('src') === src) return;

    pendingTime ||= video.currentTime;
    const { paused, playbackRate } = video;
    video.poster = `${variant}-poster.png`;
    video.src = src;
    video.playbackRate = playbackRate;
    if (!paused) {
      // A later swap can abort play(); if the browser blocks it, native play remains available.
      video.play().catch(() => {});
    }
  };
}

function setupThemeToggle() {
  const button = document.querySelector('[data-theme-toggle]');
  if (!button) return;
  const root = document.documentElement;
  const storage = getSafeStorage();
  const media = window.matchMedia('(prefers-color-scheme: dark)');
  const systemTheme = () => (media.matches ? 'dark' : 'light');
  const demos = Array.from(document.querySelectorAll('noscript[data-project-demo]'), mountProjectDemo);
  let state = createThemeState({
    systemTheme: systemTheme(),
    overrideTheme: readStoredTheme(storage),
  });

  const dispatch = (event) => {
    const step = themeReducer(state, event);
    state = step.state;
    for (const effect of step.effects) {
      applyThemeEffect(effect, { root, button, storage });
      if (effect.type === 'render-theme') {
        for (const renderDemo of demos) renderDemo(effect.theme);
      }
    }
  };

  button.addEventListener('click', () => dispatch({ type: 'theme.toggle' }));
  media.addEventListener?.('change', () => dispatch({ type: 'system-theme.changed', theme: systemTheme() }));
  window.addEventListener('pageshow', () => {
    dispatch({ type: 'theme.sync', systemTheme: systemTheme(), overrideTheme: readStoredTheme(storage) });
  });
  window.addEventListener('storage', (evt) => {
    if (evt.key && evt.key !== THEME_STORAGE_KEY) return;
    dispatch({ type: 'theme.sync', systemTheme: systemTheme(), overrideTheme: readStoredTheme(storage) });
  });
  dispatch({ type: 'chrome.mounted' });
}

function setupBackLinks() {
  document.querySelectorAll('a.back-link').forEach((link) => {
    link.addEventListener('click', (evt) => {
      if (evt.defaultPrevented || evt.button !== 0 || evt.metaKey || evt.ctrlKey || evt.shiftKey || evt.altKey) {
        return;
      }
      if (!document.referrer || window.history.length <= 1) return;
      try {
        const ref = new URL(document.referrer);
        if (ref.origin === window.location.origin && ref.pathname !== window.location.pathname) {
          evt.preventDefault();
          window.history.back();
        }
      } catch {
        // Fall back to semantic href.
      }
    });
  });
}

function setupKeyboardNavigation() {
  document.addEventListener('keydown', (evt) => {
    if (evt.metaKey || evt.ctrlKey || evt.altKey || evt.shiftKey) return;
    const target = evt.target;
    if (
      target instanceof HTMLElement &&
      (target.isContentEditable ||
        target.tagName === 'INPUT' ||
        target.tagName === 'TEXTAREA' ||
        target.tagName === 'SELECT')
    ) {
      return;
    }
    const key = evt.key.toLowerCase();
    const link = document.querySelector(`header nav a[data-nav-key="${key}"]`);
    if (link instanceof HTMLAnchorElement && link.href && link.getAttribute('aria-current') !== 'page') {
      evt.preventDefault();
      window.location.assign(link.href);
    }
  });
}

